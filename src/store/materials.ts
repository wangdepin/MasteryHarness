import * as fs from "node:fs";
import * as path from "node:path";
import { randomUUID } from "node:crypto";
import { PATHS } from "../../config.ts";
import type { MaterialStore } from "../core/ports.ts";
import type { LessonMaterial } from "../core/materials.ts";

/**
 * Lesson source material on disk (fork addition, 2026-10-24) — the
 * MaterialStore adapter (core/ports.ts), sole writer of data/materials:
 *
 *   materials/<chatId>/index.json          LessonMaterial[]
 *   materials/<chatId>/<materialId>/source.<ext>   the stored copy
 *   materials/<chatId>/<materialId>/content.md     derived text (web, image)
 *
 * Index writes are synchronous read-modify-write, so the background
 * profiler and the routes can never interleave a partial update.
 */

/** Chat and material ids are generated by the app; refuse anything that
 *  could walk out of the folder. */
const SAFE_ID = /^[A-Za-z0-9_-]+$/;
function dirOf(chatId: string): string {
	if (!SAFE_ID.test(chatId)) throw new Error(`invalid chat id: ${chatId}`);
	return path.join(PATHS.materials, chatId);
}
function materialDir(chatId: string, id: string): string {
	if (!SAFE_ID.test(id)) throw new Error(`invalid material id: ${id}`);
	return path.join(dirOf(chatId), id);
}
const indexFile = (chatId: string) => path.join(dirOf(chatId), "index.json");

function readIndex(chatId: string): LessonMaterial[] {
	const file = indexFile(chatId); // outside the try: a bad id must throw, not read as empty
	try {
		const parsed = JSON.parse(fs.readFileSync(file, "utf8"));
		return Array.isArray(parsed) ? (parsed as LessonMaterial[]) : [];
	} catch {
		return [];
	}
}

function writeIndex(chatId: string, materials: LessonMaterial[]): void {
	fs.mkdirSync(dirOf(chatId), { recursive: true });
	fs.writeFileSync(indexFile(chatId), JSON.stringify(materials, null, "\t"), "utf8");
}

export const materialStore: MaterialStore = {
	list: readIndex,

	add(chatId, input) {
		const id = `mat_${randomUUID().replace(/-/g, "").slice(0, 12)}`;
		const ext = /^\.[a-z0-9]{1,10}$/i.test(input.ext) ? input.ext.toLowerCase() : "";
		const file = `source${ext}`;
		const dir = materialDir(chatId, id);
		fs.mkdirSync(dir, { recursive: true });
		fs.writeFileSync(path.join(dir, file), input.bytes);
		const material: LessonMaterial = {
			id,
			kind: input.kind,
			name: input.name,
			file,
			...(input.url ? { url: input.url } : {}),
			...(input.mimeType ? { mimeType: input.mimeType } : {}),
			bytes: input.bytes.byteLength,
			addedAt: new Date().toISOString(),
			...(input.addedMidLesson ? { addedMidLesson: true } : {}),
			status: "reading",
		};
		writeIndex(chatId, [...readIndex(chatId), material]);
		return material;
	},

	update(chatId, id, patch) {
		const materials = readIndex(chatId);
		const i = materials.findIndex((m) => m.id === id);
		if (i < 0) return null;
		const next = { ...materials[i]!, ...patch, id };
		materials[i] = next;
		writeIndex(chatId, materials);
		return next;
	},

	remove(chatId, id) {
		const materials = readIndex(chatId);
		if (!materials.some((m) => m.id === id)) return false;
		writeIndex(chatId, materials.filter((m) => m.id !== id));
		fs.rmSync(materialDir(chatId, id), { recursive: true, force: true });
		return true;
	},

	removeAll(chatId) {
		fs.rmSync(dirOf(chatId), { recursive: true, force: true });
	},

	filePath(chatId, material) {
		return path.join(materialDir(chatId, material.id), material.file);
	},

	auxPath(chatId, id, name) {
		return path.join(materialDir(chatId, id), path.basename(name));
	},
};
